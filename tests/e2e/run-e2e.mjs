// End-to-end walkthrough in real Chromium: login -> garak bridge -> audit -> report -> PDF -> shield -> compare.
// Also checks: no console errors, no CSP violations, nothing written to browser storage, offline handling.
// Usage: node tests/e2e/run-e2e.mjs [baseUrl]   (screenshots go to tests/e2e/shots/)
import { createRequire } from "node:module";
import { execSync, spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";

const require = createRequire(import.meta.url);
const globalRoot = execSync("npm root -g").toString().trim();
const { chromium } = require(`${globalRoot}/playwright`);

const BASE = process.argv[2] || "http://localhost:5173";
const SHOTS = new URL("./shots/", import.meta.url);
await mkdir(SHOTS, { recursive: true });
let server = null;
if (!process.argv[2]) {
  server = spawn("node", ["scripts/serve.mjs"], { env: { ...process.env, RECEIPT_SIGNING_SECRET: "e2e-secret", PORT: "5173" }, stdio: "ignore" });
  await new Promise((r) => setTimeout(r, 900));
}

const results = [];
const check = (name, ok, detail = "") => { results.push({ name, ok, detail }); console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? `  (${detail})` : ""}`); };
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1360, height: 900 }, acceptDownloads: true, deviceScaleFactor: 1 });
const page = await ctx.newPage();
const consoleErrors = [];
page.on("console", (m) => { if (m.type() === "error") consoleErrors.push(m.text()); });
page.on("pageerror", (e) => consoleErrors.push(String(e)));
const shot = (name, full = true) => page.screenshot({ path: new URL(`${name}.png`, SHOTS).pathname, fullPage: full });

try {
  await page.goto(BASE + "/");
  await page.waitForURL("**/login");
  check("root redirects to /login when signed out", page.url().endsWith("/login"));
  await page.waitForSelector("#auth-title");
  await page.waitForTimeout(600);
  await shot("01-login");

  await page.goto(BASE + "/report");
  await page.waitForURL("**/login");
  check("protected route redirects to /login", page.url().endsWith("/login"));

  await page.click("#google-btn");
  check("Google button is honest when not configured", (await page.textContent("#auth-status")).includes("Google sign-in"));
  await page.fill("#email", "not-an-email");
  await page.click("#email-next");
  check("invalid email shows inline error", await page.isVisible("#email-err:not(.hide)"));

  await page.click("#guest-btn");
  await page.waitForURL("**/dashboard");
  check("guest demo lands on dashboard", true);
  await shot("02-dashboard");

  // Garak Bridge
  await page.click('a.nav-link[href="/bridge"]');
  await page.waitForSelector("#cfg-form");
  await page.click("#cfg-submit");
  await page.waitForSelector("#cfg-out .code");
  check("garak command generated by API", (await page.textContent("#cfg-out")).includes("python -m garak"));
  await page.fill("#api_key_env", "sk-live-123");
  await page.click("#cfg-submit");
  await page.waitForSelector("#api_key_env-err:not(.hide)");
  check("server rejects a pasted key as variable name (422)", true);
  await page.fill("#api_key_env", "TARGET_API_KEY");
  await page.click("#sample-btn");
  await page.waitForSelector("#imp-out table");
  check("sample garak report imported", (await page.textContent("#imp-out")).includes("leakreplay.LiteratureComplete"));
  check("garak prompts are not displayed", !(await page.content()).includes("SAMPLE PROMPT"));
  await shot("03-garak-bridge");

  // Audit model A (double-click must start only one run)
  await page.click('a.nav-link[href="/audit"]');
  await page.waitForSelector("#start-btn");
  await shot("04-audit-setup");
  await page.dblclick("#start-btn");
  await page.waitForURL("**/report", { timeout: 20000 });
  await page.waitForSelector(".gauge");
  check("audit A finished and opened the report", true);
  const riskText = await page.textContent(".gauge");
  check("model A band is CRITICAL", riskText.includes("CRITICAL"), riskText.replace(/\s+/g, " ").slice(0, 60));
  const firstRow = await page.textContent("#rec-body tr:first-child");
  check("record text masked by default", firstRow.includes("•"));
  await shot("05-report");
  const reportText = await page.textContent("main");
  check("no planted secret visible unmasked on the report", !/4532 \d{4} \d{4}/.test(reportText) && !/sk-fake-[a-z0-9]{6,}/i.test(reportText));

  // PDF download
  const [dl] = await Promise.all([page.waitForEvent("download"), page.click("#pdf-btn")]);
  const pdfPath = new URL("evidence.pdf", SHOTS).pathname;
  await dl.saveAs(pdfPath);
  await page.waitForSelector("#receipt-out .alert");
  check("PDF downloaded with signed receipt", (await page.textContent("#receipt-out")).includes("signed receipt"));

  // Shield
  await page.click('a.nav-link[href="/shield"]');
  await page.click("#build-btn");
  await page.waitForSelector("#test-form");
  await page.click("[data-try='0']");
  await page.click("[data-act='generate']");
  await page.waitForSelector("#verdict .chip");
  const verdict = await page.textContent("#verdict");
  check("Shield masks model A's leaked secret", verdict.includes("Masked"), verdict);
  check("raw reply really contained the card number", /4532 \d{4}/.test(await page.textContent("#raw-out")));
  check("shielded reply hides it", !/4532 \d{4}/.test(await page.textContent("#safe-out")));
  await shot("06-shield");

  // Compare (runs model B)
  await page.click('a.nav-link[href="/compare"]');
  await page.click("#run-pair");
  await page.waitForSelector("#sel-before", { timeout: 20000 });
  const cmp = await page.textContent("main");
  check("compare shows improvement", cmp.includes("Improved"));
  await shot("07-compare");

  for (const [p, n] of [["/method", "08-method"], ["/privacy", "09-privacy"], ["/settings", "10-settings"], ["/verify", "11-verify"]]) {
    await page.click("#user-btn");
    await page.click(`#user-menu a[href="${p}"]`);
    await page.waitForSelector("h1");
    await page.waitForTimeout(300);
    await shot(n);
  }

  // Storage must be empty
  const storage = await page.evaluate(() => ({ ls: localStorage.length, ss: sessionStorage.length, ck: document.cookie }));
  check("no localStorage / sessionStorage / cookies", storage.ls === 0 && storage.ss === 0 && storage.ck === "", JSON.stringify(storage));

  // Offline: generating a garak command fails gracefully
  await page.click('a.nav-link[href="/bridge"]');
  await ctx.setOffline(true);
  await page.click("#cfg-submit");
  await page.waitForSelector("#cfg-status .alert-error");
  check("offline request shows a friendly error", (await page.textContent("#cfg-status")).includes("Cannot reach the server"));
  check("offline banner visible", await page.isVisible("#offline"));
  await ctx.setOffline(false);

  // Mobile views
  const m = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const mp = await m.newPage();
  mp.on("console", (x) => { if (x.type() === "error") consoleErrors.push("[mobile] " + x.text()); });
  await mp.goto(BASE + "/login");
  await mp.waitForSelector("#auth-title");
  await mp.waitForTimeout(600);
  await mp.screenshot({ path: new URL("12-mobile-login.png", SHOTS).pathname, fullPage: true });
  check("login has no horizontal scroll at 390px", !(await mp.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)));
  await mp.click("#guest-btn");
  await mp.waitForURL("**/dashboard");
  await mp.screenshot({ path: new URL("13-mobile-dashboard.png", SHOTS).pathname, fullPage: true });
  const overflow = await mp.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  check("no horizontal scroll at 390px", !overflow);
  await m.close();

  const csp = consoleErrors.filter((e) => /Content Security Policy|Refused/.test(e));
  check("no CSP violations", csp.length === 0, csp.slice(0, 3).join(" | "));
  const other = consoleErrors.filter((e) => !/Content Security Policy|Refused|ERR_INTERNET_DISCONNECTED|Failed to load resource/.test(e));
  check("no console errors", other.length === 0, other.slice(0, 3).join(" | "));
} catch (e) {
  check("e2e run completed without exception", false, String(e).slice(0, 300));
  await shot("zz-failure").catch(() => {});
} finally {
  await browser.close();
  if (server) server.kill();
  await writeFile(new URL("results.json", SHOTS), JSON.stringify(results, null, 2));
  const failed = results.filter((r) => !r.ok).length;
  console.log(`\n${results.length - failed}/${results.length} checks passed`);
  process.exit(failed ? 1 : 0);
}
